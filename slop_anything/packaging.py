"""Code generation for port bindings, archives and profiling."""
from __future__ import annotations

import keyword
import re
import shutil
import tempfile
import zipapp
from pathlib import Path
from string import Template

from slop_anything import __version__
from slop_anything.catalog import Port
from slop_anything.errors import ToolError

MAX_LIFT_FILES = 2000
MAX_LIFT_BYTES = 20_000_000
LIFT_IGNORE = shutil.ignore_patterns("tests", "__pycache__", ".pytest_cache", ".slop-data", ".slop-state", "*.pyc", "*.pyz")

BRIDGE_TEMPLATE = Template(r'''"""Python binding for the $name command-line port.

Generated by slop-anything $version. Calls the port through a subprocess and
returns its standard output.
"""
from __future__ import annotations

import abc
import os
import subprocess
import sys

PORT_NAME = $name_literal
PORT_PATH = $path_literal


class PortInvocationError(RuntimeError):
    """Raised when the port exits with a non-zero status."""

    def __init__(self, returncode: int, stderr: str) -> None:
        super().__init__(f"{PORT_NAME} exited with status {returncode}")
        self.returncode = returncode
        self.stderr = stderr


class PortGateway(abc.ABC):
    """Transport abstraction for port invocations."""

    @abc.abstractmethod
    def invoke(self, args: list[str], timeout: float) -> str:
        """Runs the port and returns its standard output."""


class SubprocessPortGateway(PortGateway):
    """Runs the port as a child interpreter with standard input closed."""

    def invoke(self, args: list[str], timeout: float) -> str:
        completed = subprocess.run(
            [sys.executable, PORT_PATH, *args],
            stdin=subprocess.DEVNULL,
            capture_output=True,
            timeout=timeout,
            env={**os.environ, "PYTHONIOENCODING": "utf-8", "PYTHONDONTWRITEBYTECODE": "1"},
        )
        if completed.returncode != 0:
            raise PortInvocationError(completed.returncode, completed.stderr.decode("utf-8", "replace"))
        return completed.stdout.decode("utf-8", "replace").replace("\r\n", "\n")


_GATEWAY = SubprocessPortGateway()


def $function(*args: object, timeout: float = 30.0) -> str:
    """Runs the $name port with ``args`` and returns its standard output."""
    return _GATEWAY.invoke([str(arg) for arg in args], timeout)


__all__ = ["PORT_NAME", "PORT_PATH", "PortInvocationError", "$function"]
''')

LIFT_BOOTSTRAP = Template(r'''"""Self-contained launcher for the $name port."""
import os
import runpy
import sys
import tempfile
import zipfile

PORT_NAME = $name_literal


def main():
    sys.dont_write_bytecode = True
    archive = os.path.dirname(os.path.abspath(__file__))
    data_dir = os.environ.get("SLOP_DATA_DIR") or os.path.join(os.getcwd(), ".slop-data", PORT_NAME)
    os.makedirs(data_dir, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".runtime-", dir=data_dir, ignore_cleanup_errors=True) as runtime:
        with zipfile.ZipFile(archive) as bundle:
            bundle.extractall(runtime, [member for member in bundle.namelist() if member.startswith("port/")])
        target = os.path.join(runtime, "port")
        sys.argv = [target, *sys.argv[1:]]
        runpy.run_path(target, run_name="__main__")


main()
''')

PROFILE_BOOTSTRAP = r'''
import cProfile, json, pstats, runpy, sys
port, out, top = sys.argv[1], sys.argv[2], int(sys.argv[3])
sys.argv = [port, *sys.argv[4:]]
sys.dont_write_bytecode = True
profiler = cProfile.Profile()
code = 0
try:
    profiler.runcall(runpy.run_path, port, run_name="__main__")
except SystemExit as stop:
    if isinstance(stop.code, int):
        code = stop.code
    elif stop.code is not None:
        print(stop.code, file=sys.stderr)
        code = 1
sys.stdout.flush()
rows = []
for (file, line, name), (primitive, total, own, cumulative, _) in pstats.Stats(profiler).stats.items():
    if file.startswith("<frozen ") or file.endswith("runpy.py") or name == "<built-in method builtins.exec>":
        continue
    rows.append({"function": name, "file": file, "line": line, "calls": total,
                 "tottime_ms": round(own * 1000, 3), "cumtime_ms": round(cumulative * 1000, 3)})
rows.sort(key=lambda row: (-row["cumtime_ms"], -row["tottime_ms"], row["function"]))
with open(out, "w", encoding="utf-8") as handle:
    json.dump(rows[:top], handle)
sys.exit(code)
'''


def identifier(name: str) -> str:
    """A valid Python identifier derived from a port name."""
    ident = re.sub(r"\W", "_", name)
    if not ident or ident[0].isdigit() or keyword.iskeyword(ident):
        ident = f"port_{ident}"
    return ident


def render_bridge(port: Port) -> tuple[str, str]:
    """Returns (function name, module source) and compile-checks the source."""
    function = identifier(port.name)
    source = BRIDGE_TEMPLATE.substitute(
        name=port.name, version=__version__, name_literal=repr(port.name),
        path_literal=repr(str(port.path)), function=function,
    )
    compile(source, f"{function}.py", "exec")
    return function, source


def build_archive(port: Port, target: Path) -> dict:
    """Builds a runnable zipapp of the port at ``target``."""
    count = size = 0
    for file in port.path.rglob("*"):
        if file.is_file() and not any(part in {"tests", "__pycache__", ".slop-data", ".slop-state"} for part in file.parts):
            count += 1
            size += file.stat().st_size
    if count > MAX_LIFT_FILES or size > MAX_LIFT_BYTES:
        raise ToolError(f"port {port.name!r} is too large to archive ({count} files, {size} bytes)")
    target.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".staging-", dir=target.parent, ignore_cleanup_errors=True) as staging:
        root = Path(staging)
        shutil.copytree(port.path, root / "port", ignore=LIFT_IGNORE)
        bootstrap = LIFT_BOOTSTRAP.substitute(name=port.name, name_literal=repr(port.name))
        compile(bootstrap, "__main__.py", "exec")
        (root / "__main__.py").write_text(bootstrap, encoding="utf-8")
        files = sum(1 for item in root.rglob("*") if item.is_file())
        zipapp.create_archive(root, target, compressed=True)
    return {"archive": str(target), "bytes": target.stat().st_size, "files": files}
